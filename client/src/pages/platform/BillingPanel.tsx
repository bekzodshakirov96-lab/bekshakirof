import { useRef, useState } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { CreditCard, ExternalLink, RefreshCw } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog";
import {
  billingMoney,
  type BillingView,
  type BillingProvider,
} from "@shared/billing";
import { api, date, ErrorMessage, Loading } from "./ui";
import { ConsoleSection } from "./console-ui";

export function BillingPanel({
  companyId,
  refresh,
}: {
  companyId: string;
  refresh: () => unknown;
}) {
  const [page, setPage] = useState(1);
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const requestKey = useRef<string | null>(null);
  const cache = useQueryClient();
  const query = useQuery({
    queryKey: ["platform", "billing", companyId, page],
    queryFn: () => api<BillingView>(`/billing?page=${page}`),
    retry: false,
    refetchInterval: 15000,
  });
  const data = query.data;
  const pending = data?.pendingOrder;
  const quotedAmount = pending?.amountTiyin ?? data?.price?.amountTiyin;
  async function update() {
    await cache.invalidateQueries({
      queryKey: ["platform", "billing", companyId],
    });
    await refresh();
  }
  async function pay(provider: BillingProvider) {
    if (busy) return;
    setBusy(true);
    setError("");
    requestKey.current ??= crypto.randomUUID();
    try {
      const order = await api<{ checkoutUrl: string; amountTiyin: number }>(
        "/billing/orders",
        {
          provider,
          requestKey: requestKey.current,
        }
      );
      if (order.amountTiyin !== quotedAmount) {
        await update();
        throw Error(
          "Narx yangilandi. Yangi summani tekshirib, to‘lovni qayta davom ettiring."
        );
      }
      // Only provider-owned checkout hosts generated by our server may open.
      const url = new URL(order.checkoutUrl);
      if (
        url.protocol !== "https:" ||
        !["checkout.paycom.uz", "test.paycom.uz", "my.click.uz"].includes(
          url.hostname
        )
      )
        throw Error("To‘lov manzili xato.");
      window.location.assign(url.href);
    } catch (e) {
      setError((e as Error).message);
      setBusy(false);
    }
  }
  return (
    <ConsoleSection
      title="Obuna va to‘lovlar"
      subtitle="Bir kalendar oy · so‘mda · avtomatik yechishsiz"
      action={
        <Button
          variant="outline"
          size="sm"
          className="h-8 text-xs"
          disabled={
            !data?.price || !Object.values(data?.providers ?? {}).some(Boolean)
          }
          onClick={() => {
            setError("");
            requestKey.current = null;
            setOpen(true);
          }}
        >
          <CreditCard className="size-3.5" />
          Obunani to‘lash
        </Button>
      }
    >
      <div className="space-y-4 p-4">
        {query.isPending ? (
          <Loading />
        ) : query.error ? (
          <ErrorMessage message={query.error.message} />
        ) : (
          data && (
            <>
              <div className="flex flex-wrap items-start justify-between gap-3">
                <div>
                  <p className="text-[11px] text-muted-foreground">
                    Oylik obuna
                  </p>
                  <p className="mt-1 text-xl font-semibold tabular-nums">
                    {data.price
                      ? billingMoney(data.price.amountTiyin)
                      : "Narx belgilanmagan"}
                  </p>
                </div>
                <Button
                  variant="ghost"
                  size="sm"
                  className="h-8 text-xs"
                  disabled={query.isFetching}
                  onClick={() => void update()}
                >
                  <RefreshCw className="size-3.5" />
                  Holatni tekshirish
                </Button>
              </div>
              <p className="text-[11px] leading-relaxed text-muted-foreground">
                To‘lov Payme yoki Click sahifasida amalga oshiriladi. Obuna
                provayder to‘lovni tasdiqlagach uzayadi. Amaldagi muddatga bir
                oy qo‘shiladi; bepul sinov kunlari saqlanadi.
              </p>
              {data.mode !== "live" && (
                <p className="rounded-lg border bg-muted/30 p-3 text-xs">
                  {data.mode === "test"
                    ? "Sinov rejimi. Bu to‘lovlar haqiqiy tushum hisoblanmaydi."
                    : "Onlayn to‘lov hali yoqilmagan. Merchant rekvizitlari sozlangach to‘lash mumkin bo‘ladi."}
                </p>
              )}
              {!data.price && (
                <p className="text-xs text-muted-foreground">
                  Oylik narxni Super admin belgilaydi.
                </p>
              )}
              {data.price &&
                !Object.values(data.providers).some(Boolean) &&
                data.mode !== "off" && (
                  <p className="text-xs text-muted-foreground">
                    Payme va Click ulanishi sozlanmoqda.
                  </p>
                )}
              {data.orders.length ? (
                <div className="overflow-x-auto">
                  <table className="w-full min-w-[570px] text-left text-xs">
                    <caption className="sr-only">
                      Obuna to‘lovlari tarixi
                    </caption>
                    <thead className="border-y bg-muted/30 text-[11px] text-muted-foreground">
                      <tr>
                        {[
                          "Buyurtma / sana",
                          "Usul",
                          "Summa",
                          "Holat",
                          "Obuna davri",
                          "",
                        ].map((x, i) => (
                          <th
                            key={i}
                            scope="col"
                            className="px-3 py-2 font-medium"
                          >
                            {x}
                          </th>
                        ))}
                      </tr>
                    </thead>
                    <tbody className="divide-y">
                      {data.orders.map(o => (
                        <tr key={o.id}>
                          <td className="px-3 py-3">
                            <span
                              className="font-mono text-[10px]"
                              title={o.id}
                            >
                              #{o.id.slice(0, 8)}
                            </span>
                            <p className="mt-1 text-muted-foreground">
                              {date(o.createdAt)}
                            </p>
                          </td>
                          <td className="px-3 py-3">
                            {o.provider === "payme" ? "Payme" : "Click"}
                            {o.mode === "test" && (
                              <span className="block text-[10px] text-amber-600">
                                Sinov
                              </span>
                            )}
                          </td>
                          <td className="px-3 py-3 whitespace-nowrap font-medium">
                            {billingMoney(o.amountTiyin)}
                          </td>
                          <td
                            className={`px-3 py-3 ${o.state === "paid" ? "text-emerald-600" : o.state === "cancelled" ? "text-muted-foreground" : "text-amber-600"}`}
                          >
                            {o.state === "paid"
                              ? "To‘langan"
                              : o.state === "cancelled"
                                ? "Bekor qilingan"
                                : o.needsReview ? "Provayder holati tekshirilishi kerak"
                                : o.expiresAt <= Date.now() && !o.checkoutUrl
                                  ? "Muddati tugagan"
                                  : "Kutilmoqda"}
                          </td>
                          <td className="px-3 py-3 whitespace-nowrap">
                            {o.periodStart
                              ? `${date(o.periodStart)} — ${date(o.periodEnd)}`
                              : "—"}
                          </td>
                          <td className="px-3 py-3">
                            {o.checkoutUrl && (
                              <a
                                href={o.checkoutUrl}
                                className="inline-flex items-center gap-1 whitespace-nowrap underline underline-offset-4"
                              >
                                Davom ettirish
                                <ExternalLink className="size-3" />
                              </a>
                            )}
                            {o.needsReview && <p className="text-xs text-muted-foreground">Super admin bilan bog‘laning. Tekshiruv tugamaguncha takror to‘lamang.</p>}
                            {o.state === "pending" && !o.needsReview && (
                              <Button
                                variant="ghost"
                                size="sm"
                                className="mt-1 h-7 text-[11px]"
                                disabled={busy}
                                onClick={async () => {
                                  setBusy(true);
                                  setError("");
                                  try {
                                    await api(
                                      `/billing/orders/${o.id}/cancel`,
                                      {}
                                    );
                                    await update();
                                  } catch (e) {
                                    setError((e as Error).message);
                                  } finally {
                                    setBusy(false);
                                  }
                                }}
                              >
                                Bekor qilish
                              </Button>
                            )}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              ) : (
                <p className="rounded-lg border border-dashed p-4 text-xs text-muted-foreground">
                  Hali obuna to‘lovi yo‘q. To‘lovlar shu yerda saqlanadi.
                </p>
              )}
              <div className="flex items-center justify-between text-[11px] text-muted-foreground">
                <span>
                  {data.total} ta buyurtma · {data.page}/{data.pageCount}
                </span>
                <div className="flex gap-2">
                  <Button
                    variant="outline"
                    size="sm"
                    className="h-7 text-xs"
                    disabled={data.page <= 1}
                    onClick={() => setPage(data.page - 1)}
                  >
                    Oldingi
                  </Button>
                  <Button
                    variant="outline"
                    size="sm"
                    className="h-7 text-xs"
                    disabled={data.page >= data.pageCount}
                    onClick={() => setPage(data.page + 1)}
                  >
                    Keyingi
                  </Button>
                </div>
              </div>
            </>
          )
        )}
        {!open && error && <ErrorMessage message={error} />}
        <p className="border-t pt-3 text-[11px] text-muted-foreground">
          Bu platforma obunasi. Firma kassasi, savdosi va qarzdorlik hisoblariga
          yozilmaydi.
        </p>
      </div>
      <Dialog
        open={open}
        onOpenChange={value => {
          if (!busy) setOpen(value);
        }}
      >
        <DialogContent className="sm:max-w-md">
          <DialogHeader>
            <DialogTitle>Obunani to‘lash</DialogTitle>
            <DialogDescription>
              Bir kalendar oy uchun to‘lov usulini tanlang.
            </DialogDescription>
          </DialogHeader>
          <div className="space-y-4">
            <div className="rounded-lg border bg-muted/30 p-4">
              <p className="text-xs text-muted-foreground">Jami to‘lov</p>
              <p className="mt-1 text-2xl font-semibold">
                {quotedAmount ? billingMoney(quotedAmount) : "—"}
              </p>
              <p className="mt-2 text-xs text-muted-foreground">
                {data?.mode === "test" ? "Sinov rejimi · " : ""}1 oy · UZS
              </p>
            </div>
            {pending && (
              <p className="text-xs text-amber-600">
                Ochiq buyurtma bor. O‘sha usulni tanlang yoki tarixdagi
                buyurtmani bekor qiling.
              </p>
            )}
            {error && <ErrorMessage message={error} />}
            <div className="grid grid-cols-2 gap-3">
              <Button
                className="h-11"
                disabled={
                  busy ||
                  !data?.providers.payme ||
                  (!!pending &&
                    (pending.provider !== "payme" ||
                      pending.mode !== data.mode))
                }
                onClick={() => void pay("payme")}
              >
                Payme orqali
              </Button>
              <Button
                variant="outline"
                className="h-11"
                disabled={
                  busy ||
                  !data?.providers.click ||
                  (!!pending &&
                    (pending.provider !== "click" ||
                      pending.mode !== data.mode))
                }
                onClick={() => void pay("click")}
              >
                Click orqali
              </Button>
            </div>
            <p className="text-[11px] leading-relaxed text-muted-foreground">
              Karta ma’lumotlari BiznesControl’da saqlanmaydi. To‘lovni
              provayder sahifasida o‘zingiz tasdiqlaysiz.
            </p>
          </div>
        </DialogContent>
      </Dialog>
    </ConsoleSection>
  );
}
